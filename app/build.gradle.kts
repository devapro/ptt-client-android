import java.time.LocalDateTime
import java.time.format.DateTimeFormatter
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

/**
 * `version.properties` (versionName/versionCode) and `relay.properties` (the default relay) are
 * parsed once, in `gradle/relay-defaults.gradle.kts`, and shared by every module that needs them
 * (`:app`, `:shared`, `:desktopApp`) — see that file for why, and for the exact parsing rules
 * (F-Droid builds a plain checkout with no Gradle properties set, so both files have to keep
 * working read directly off disk).
 */
apply(from = "$rootDir/gradle/relay-defaults.gradle.kts")

val appVersionName: String by extra
val appVersionCode: Int by extra
val defaultRelayHost: String by extra
val defaultRelayPort: Int by extra
val defaultRelayTls: Boolean by extra

/**
 * Wall-clock time of this Gradle invocation, stamped into the APK file names below.
 *
 * Read once here rather than per variant, so every APK produced by one invocation carries the
 * same stamp, and in the builder's own timezone rather than UTC — the question it answers is
 * "when did I build this", asked by someone holding the file.
 */
val buildTimestamp: String = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd-HHmm"))

plugins {
    alias(libs.plugins.androidApplication)
    alias(libs.plugins.jetbrainsKotlinAndroid)
    alias(libs.plugins.jetbrainsKotlinCompose)
    alias(libs.plugins.jetbrainsKotlinSerialization)
    // Only for the `compose.components.resources` dependency below: :shared's Compose
    // Multiplatform `Res` accessor (StringResource/PluralStringResource) is generated by this
    // plugin, and :shared's own dependency on the resources library is `implementation`-scoped
    // so it does not reach :app transitively. :app is still a plain Android application module,
    // not a KMP one — this plugin is applied purely for the dependency accessor it provides.
    alias(libs.plugins.composeMultiplatform)
}

android {
    namespace = "com.github.devapro.pttdroid"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.github.devapro.pttdroid"
        minSdk = 24
        targetSdk = 36
        versionCode = appVersionCode
        versionName = appVersionName

        buildConfigField("String", "DEFAULT_RELAY_HOST", "\"$defaultRelayHost\"")
        buildConfigField("int", "DEFAULT_RELAY_PORT", "$defaultRelayPort")
        buildConfigField("boolean", "DEFAULT_RELAY_TLS", "$defaultRelayTls")

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
    }

    /**
     * Release signing, supplied by the environment so no key material is ever in the repository.
     *
     * Android will not install an update signed with a different key, so this key has to outlive
     * every release. It lives in CI secrets; see `docs/fdroid.md`.
     *
     * When the variables are absent the config is simply not created and `assembleRelease`
     * produces an unsigned APK — which is the right outcome for a local build, and which the
     * publishing workflow checks for rather than shipping by accident.
     */
    val keystorePath: String? = System.getenv("PTT_KEYSTORE_PATH")
    if (!keystorePath.isNullOrBlank()) {
        signingConfigs {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("PTT_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("PTT_KEY_ALIAS")
                keyPassword = System.getenv("PTT_KEY_PASSWORD")
                // minSdk is 24, so the v1 JAR signature nothing above API 23 reads is dead
                // weight; AGP drops it here regardless of what this flag says. v3 carries the
                // rotation proof, which matters for a key that has to outlive every release.
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = signingConfigs.findByName("release")
        }
    }

    /**
     * Keep the Play dependency-metadata blob out of the APK.
     *
     * It is an encrypted blob whose contents cannot be reproduced from source, which breaks
     * F-Droid's reproducible-build check, and it exists to report the dependency tree to Google
     * Play — a store this app is not on.
     */
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

/**
 * Name every APK `PTTdroid-<versionName>-<yyyyMMdd-HHmm>-<variant>.apk` instead of AGP's default
 * `app-<variant>.apk`, so a copy that has left the build directory still says which version it is
 * and when it was built — neither of which a tester holding a shared `app-debug.apk` can recover.
 *
 * This renames the *file* only. Nothing time-dependent goes into the APK, so a release build is
 * still byte-for-byte reproducible, which is what F-Droid checks; the release workflow republishes
 * it as `com.github.devapro.pttdroid_<versionCode>.apk` regardless, and resolves this name from
 * `output-metadata.json` rather than hardcoding it.
 *
 * A name that changes every build does not pile APKs up: the previous one is a registered task
 * output, so Gradle's stale-output cleanup removes it and the directory keeps exactly one APK per
 * variant. Nothing can hardcode the name, though — scripts glob `PTTdroid-*-<variant>.apk` or read
 * `output-metadata.json`.
 */
androidComponents {
    onVariants { variant ->
        variant.outputs.forEach { output ->
            output.outputFileName.set("PTTdroid-$appVersionName-$buildTimestamp-${variant.name}.apk")
        }
    }
}

